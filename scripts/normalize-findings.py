#!/usr/bin/env python3

from __future__ import annotations

import json
import re
import sys
from datetime import date
from pathlib import Path
from typing import Any

ALLOWED_DATES = date.today().isoformat()

# sqlmap log keywords we treat as "real" injection verdicts.
SQLMAP_INJ_LINE = re.compile(
    r"(?P<method>GET|POST)\s+parameter\s+['\"](?P<param>[^'\"]+)['\"]\s+"
    r"(?:is\s+vulnerable|appears\s+to\s+be\s+'?(?P<technique>[^'\"]+?)'?\s+injectable)",
    re.IGNORECASE,
)
SQLMAP_VULN_LINE = re.compile(
    r"parameter\s+['\"](?P<param>[^'\"]+)['\"]?\s+is\s+vulnerable",
    re.IGNORECASE,
)
SQLMAP_DBMS_LINE = re.compile(r"back-end DBMS(?:\s+is)?\s*[:=]?\s*(?P<dbms>.+)", re.IGNORECASE)

# ffuf path heuristics for severity bump.
SENSITIVE_PATH_HINTS = {"admin", "login", "dashboard", "config", "internal", "private"}
# ffuf statuses we consider "interesting" (everything else dropped).
FFUF_INTERESTING_STATUS = {200, 201, 204, 301, 302, 303, 307, 308, 401, 403}

DYNAMIC_TOOL = True
TARGET_BASES = {
    "juice-shop": "http://juice-shop.targets.svc.cluster.local:3000",
    "dvwa": "http://dvwa.targets.svc.cluster.local:80",
}
SEVERITY_TO_PRIORITY = {
    "Critical": 90,
    "High": 70,
    "Medium": 50,
    "Low": 30,
    "Info": 15,
}


def priority_tag(severity: str) -> str:
    """Return the `priority-NN` DefectDojo tag for a severity string.
    Unknown severities default to Medium (50) so they still route."""
    n = SEVERITY_TO_PRIORITY.get((severity or "").capitalize(), 50)
    return f"priority-{n}"


def tags_with_priority(severity: str, *extra: str) -> list[str]:
    """Build a `tags` list with the priority stamp appended at the end."""
    return list(extra) + [priority_tag(severity)]


def _today() -> str:
    return ALLOWED_DATES


def _emit_norm_file(out_path: Path, tool: str, target_short: str, findings: list[dict]) -> dict:
    doc = {
        "name": f"{tool} normalized",
        "type": "Generic Findings Import",
        "version": "1.0",
        "description": (
            f"Normalized findings from {tool} run against {target_short}. "
            f"Generated by scripts/normalize-findings.py."
        ),
        "dynamic_tool": DYNAMIC_TOOL,
        "findings": findings,
    }
    out_path.write_text(json.dumps(doc, indent=2), encoding="utf-8")
    return doc


# ---------------------------------------------------------------- sqlmap ----

def normalize_sqlmap(raw_path: Path, target_short: str) -> list[dict]:
    text = raw_path.read_text(errors="replace")
    if not text.strip():
        return []

    dbms: str | None = None
    m = SQLMAP_DBMS_LINE.search(text)
    if m:
        dbms = m.group("dbms").strip().rstrip(".")

    findings: list[dict] = []
    seen_params: set[str] = set()
    for m in SQLMAP_INJ_LINE.finditer(text):
        param = m.group("param")
        if param in seen_params:
            continue
        seen_params.add(param)
        technique = (m.group("technique") or "boolean-based blind").strip().strip("'")
        severity = "High"  # confirm by --technique level if true positive
        title = f"SQL Injection via {m.group('method')} parameter '{param}'"
        description_lines = [
            f"sqlmap reports the {m.group('method')} parameter '{param}' as "
            f"{technique} injectable.",
        ]
        if dbms:
            description_lines.append(f"Inferred back-end DBMS: {dbms}.")
        # pull the surrounding log context (5 lines around the match) for forensics
        start, end = max(0, m.start() - 200), min(len(text), m.end() + 600)
        description_lines.append("Excerpt:\n" + text[start:end].rstrip())
        findings.append(
            {
                "title": title,
                "severity": severity,
                "description": "\n".join(description_lines),
                "date": _today(),
                "cwe": 89,
                "impact": (
                    "Successful SQL injection allows arbitrary SQL read access "
                    "against the back-end database (data exfiltration, possible "
                    "RCE depending on DB privileges)."
                ),
                "mitigation": (
                    "Use parameterized queries / prepared statements with bound "
                    "parameters for all user-controlled input; enforce strict input "
                    "validation and least-privilege DB credentials."
                ),
                "param": param,
                "endpoints": [
                    f"{TARGET_BASES.get(target_short, f'http://{target_short}.targets.svc.cluster.local')}"
                    f"/rest/products/search?q={param}"
                ],
                "tags": tags_with_priority(severity, "sqlmap", target_short),
                "unique_id_from_tool": f"sqlmap-{target_short}-{param}",
                "active": True,
                # sqlmap explicitly declared this parameter injectable -- that
                # is a tool-confirmed exploit, so mark verified=true. Without
                # this, DefectDojo's reimport path marks the finding as
                # 'Inactive, Mitigated' on subsequent runs once the live
                # response shape changes (the reimport compares payloads).
                "verified": True,
            }
        )

    # Fallback: if regex above missed it, also honor the generic "is vulnerable" line.
    for m in SQLMAP_VULN_LINE.finditer(text):
        param = m.group("param")
        if param in seen_params:
            continue
        seen_params.add(param)
        sev = "High"
        findings.append(
            {
                "title": f"SQL Injection via parameter '{param}'",
                "severity": sev,
                "description": f"sqlmap flagged parameter '{param}' as vulnerable.\nExcerpt:\n"
                + text[max(0, m.start() - 200):min(len(text), m.end() + 600)].rstrip(),
                "date": _today(),
                "cwe": 89,
                "param": param,
                "endpoints": [
                    f"{TARGET_BASES.get(target_short, f'http://{target_short}.targets.svc.cluster.local')}"
                    f"/rest/products/search?q={param}"
                ],
                "tags": tags_with_priority(sev, "sqlmap", target_short),
                "unique_id_from_tool": f"sqlmap-{target_short}-{param}",
                "active": True,
                "verified": True,
            }
        )
    return findings


# ----------------------------------------------------------------- ffuf ----

def normalize_ffuf(raw_path: Path, target_short: str) -> list[dict]:
    try:
        data = json.loads(raw_path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return []

    results: list[dict] = data.get("results", []) if isinstance(data, dict) else data
    if not isinstance(results, list):
        return []

    base = TARGET_BASES.get(target_short, f"http://{target_short}.targets.svc.cluster.local")
    discovered_endpoints: list[dict] = []
    endpoint_urls: list[str] = []

    for r in results:
        try:
            status = int(r.get("status", 0))
        except (TypeError, ValueError):
            status = 0
        if status not in FFUF_INTERESTING_STATUS:
            continue
        word = str(r.get("input", {}).get("FUZZ", "")).strip()
        if not word:
            continue
        path = f"/{word}"
        url = f"{base}{path}"

        length = r.get("length", "?")
        words = r.get("words", "?")
        lines = r.get("lines", "?")
        content_type = r.get("content-type", "n/a")

        discovered_endpoints.append({
            "path": path,
            "status": status,
            "url": url,
            "length": length,
            "words": words,
            "lines": lines,
            "content_type": content_type,
        })
        endpoint_urls.append(url)

    if not discovered_endpoints:
        return []

    endpoint_lines = [
        f" - {ep['path']} (HTTP {ep['status']}, len: {ep['length']}, content-type: {ep['content_type']})"
        for ep in discovered_endpoints
    ]
    description = (
        f"ffuf discovered {len(discovered_endpoints)} endpoint(s) on target {target_short} ({base}):\n\n"
        + "\n".join(endpoint_lines)
    )

    severity = "Info"
    return [
        {
            "title": f"Endpoint Discovery Summary: {len(discovered_endpoints)} endpoints found on {target_short}",
            "severity": severity,
            "description": description,
            "date": _today(),
            "cwe": 200,
            "impact": (
                "Discovered endpoints provide structural information about the target application. "
                "Review to ensure no unauthenticated or sensitive endpoints are publicly exposed."
            ),
            "mitigation": (
                "Ensure proper access control and authentication on internal/admin endpoints."
            ),
            "payload": "FUZZ",
            "param": "FUZZ",
            "endpoints": endpoint_urls[:10],
            "tags": tags_with_priority(severity, "ffuf", target_short, "endpoint-summary"),
            "unique_id_from_tool": f"ffuf-summary-{target_short}",
            "active": True,
            "verified": False,
        }
    ]


# --------------------------------------------------------------- xss ----

def normalize_xss(raw_path: Path, target_short: str) -> list[dict]:
    """Parse XSStrike's text-mode stdout (no JSON output exists in XSStrike).

    Phase 0 fix: previous version assumed `--json` mode (which actually
    means "POST data is JSON" in xsstrike), so the per-URL run produced
    empty JSON output and the JSON parser silently returned []. The xss-job
    now emits the full text stdout between markers; here we parse it as a
    state machine:

        [!] Testing parameter: q
        [+] WAF Status: Offline
        [-] No reflection found                  <-- not a finding, skip
        ...
        [+] Payload: <script>...</script>
        Efficiency: 95
        Confidence: 80
        ----                                      <-- per-URL separator
        [!] Testing parameter: name
        [+] Payload: <svg onload=...>
        Efficiency: 80
        Confidence: 70

    Each `Payload:` line followed by Efficiency/Confidence becomes one
    finding attributed to the most-recent `Testing parameter:` line.
    Lines that don't match this pattern are dropped (WAF status info,
    "no reflection" messages, DOM warnings, etc).
    """
    text = raw_path.read_text(encoding="utf-8", errors="replace")
    if not text.strip():
        return []

    # Match the param context line (case-insensitive; XSStrike prints "[!]"
    # or "[i]" prefix depending on console log level):
    param_line_re = re.compile(
        r"\[(?:!|i|\+|-|\*)\]\s*Testing\s+parameter:\s*(?P<param>\S+)",
        re.IGNORECASE,
    )
    # Match the "Payload:" success line. XSStrike uses "[+]" prefix here.
    payload_re = re.compile(
        r"\[\+\]\s*Payload:\s*(?P<payload>.+?)\s*$",
        re.IGNORECASE,
    )
    # Match Efficiency / Confidence follow-on lines.
    efficiency_re = re.compile(r"Efficiency:\s*(?P<n>\d+)", re.IGNORECASE)
    confidence_re = re.compile(r"Confidence:\s*(?P<n>\d+)", re.IGNORECASE)
    # Match the URL we are currently scanning. xsstrike prints `-u <url>`
    # indirectly only via error messages, so we use a heuristic: when the
    # line `[!] Target URL: <url>` appears, capture it. Fallback: use the
    # placeholder endpoint base for the target_short.
    target_re = re.compile(r"(?:Target|target)[\s_-]*URL\s*[:=]?\s*(?P<url>https?://\S+)", re.IGNORECASE)

    findings: list[dict] = []
    current_param: str | None = None
    current_target: str | None = None
    pending: dict | None = None  # in-progress finding awaiting Eff/Conf
    base = TARGET_BASES.get(target_short, f"http://{target_short}.targets.svc.cluster.local")

    def flush(p: dict | None):
        if p is None:
            return
        # Trailing Eff/Conf didn't arrive? still emit (degraded finding).
        findings.append(p)

    for raw_line in text.splitlines():
        line = raw_line.rstrip()
        if not line:
            continue
        # Track current param context
        m = param_line_re.search(line)
        if m:
            current_param = m.group("param").strip("'\"")
            continue
        m = target_re.search(line)
        if m:
            current_target = m.group("url").strip()
            continue
        # Payload line -> start a new pending finding (flushing any
        # previous one that didn't get its trailing Eff/Conf)
        m = payload_re.search(line)
        if m:
            flush(pending)
            pending = {
                "title": f"Reflected XSS on parameter '{current_param or '?'}'",
                "severity": "High",
                "description": (
                    f"XSStrike generated a working XSS payload for parameter "
                    f"'{current_param or '?'}':\n"
                    f"Payload: {m.group('payload')}"
                ),
                "date": _today(),
                "cwe": 79,
                "impact": (
                    "A reflected cross-site scripting vulnerability allows an "
                    "attacker to inject scripting that executes in a victim's "
                    "browser (session stealing, defacement, phishing payloads)."
                ),
                "mitigation": (
                    "Apply context-aware output encoding / HTML escaping of "
                    "user-controlled input (and CSP as defense-in-depth)."
                ),
                "param": current_param,
                "payload": m.group("payload"),
                "endpoints": [current_target or f"{base}/"],
                "tags": tags_with_priority("High", "xss", "xsstrike", target_short),
                # xss payload confirmation from tool = verified True.
                # See prior Phase 0 fix; this stops DefectDojo's reimport from
                # silently closing the finding as 'Inactive, Mitigated'.
                "unique_id_from_tool": (
                    f"xss-{target_short}-{current_param or 'any'}"
                    f"-{hash(m.group('payload')) & 0xFFFF:x}"
                ),
                "active": True,
                "verified": True,
            }
            continue
        # Eff / Conf follow-on lines attach to the pending finding.
        if pending is not None:
            m = efficiency_re.search(line)
            if m:
                pending["description"] += f"\nEfficiency: {m.group('n')}"
                continue
            m = confidence_re.search(line)
            if m:
                pending["description"] += f"\nConfidence: {m.group('n')}"
                continue
        # A run-separator `----` line ends the current finding context.
        if line.strip().startswith("----") or line.strip() == "":
            flush(pending)
            pending = None
    flush(pending)
    return findings


# ------------------------------------------------------------- crawler -----

def normalize_crawler(raw_path: Path, target_short: str) -> list[dict]:
    """Crawler output is just a list of URLs. We emit one Info finding per
    discovered URL so it lands in DefectDojo and can be used as feed for
    future scans. Heavy by design — comment the call in scan-all.sh if not
    wanted."""
    urls = [
        line.strip()
        for line in raw_path.read_text(errors="replace").splitlines()
        if line.strip()
    ]
    base = TARGET_BASES.get(target_short, f"http://{target_short}.targets.svc.cluster.local")
    findings: list[dict] = []
    for idx, u in enumerate(urls):
        endpoint = u if u.startswith("http") else f"{base}{u if u.startswith('/') else '/' + u}"
        findings.append(
            {
                "title": f"Discovered URL: {endpoint}",
                "severity": "Info",
                "description": f"katana crawler discovered endpoint {endpoint}.",
                "date": _today(),
                "endpoints": [endpoint],
                "tags": tags_with_priority("Info", "crawler", "katana", target_short),
                "unique_id_from_tool": f"katana-{target_short}-{idx}",
                "active": True,
                "verified": False,
            }
        )
    return findings


NORMALIZERS = {
    "sqlmap": normalize_sqlmap,
    "ffuf": normalize_ffuf,
    "xss": normalize_xss,
    "crawler": normalize_crawler,
}


def main(argv: list[str]) -> int:
    if len(argv) < 5:
        sys.stderr.write(
            "usage: normalize-findings.py <tool> <raw_file> <out_file> <target_short> [--db <path>] [--run-id <N>]\n"
            f"tool must be one of: {', '.join(NORMALIZERS)}\n"
        )
        return 2

    tool, raw_file, out_file, target_short = argv[1:5]

    # Optional flags: --db <path> --run-id <N>
    db_path = None
    run_id = None
    i = 5
    while i < len(argv):
        if argv[i] == "--db" and i + 1 < len(argv):
            db_path = argv[i + 1]
            i += 2
        elif argv[i] == "--run-id" and i + 1 < len(argv):
            run_id = int(argv[i + 1])
            i += 2
        else:
            i += 1

    if tool not in NORMALIZERS:
        sys.stderr.write(f"unknown tool '{tool}'. known: {list(NORMALIZERS)}\n")
        return 2

    raw_path = Path(raw_file)
    out_path = Path(out_file)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    findings = NORMALIZERS[tool](raw_path, target_short)
    doc = _emit_norm_file(out_path, tool, target_short, findings)
    sys.stdout.write(
        f"normalize-findings.py: {tool} -> {len(findings)} findings"
        f" written to {out_path}\n"
    )
    # Also dump a short count to stderr so callers can see it via bash backticks.
    sys.stderr.write(f"{len(findings)}\n")

    # ── Store findings in SQLite ────────────────────────────────────
    if db_path and findings:
        try:
            # Import the voc-db module from the same directory
            script_dir = Path(__file__).resolve().parent
            import importlib.util
            spec = importlib.util.spec_from_file_location("voc_db", script_dir / "voc-db.py")
            voc_db = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(voc_db)

            conn = voc_db.init_db(db_path)
            count = voc_db.store_findings(conn, run_id, tool, target_short, findings)
            conn.close()
            sys.stdout.write(f"normalize-findings.py: stored {count} findings in SQLite ({db_path})\n")
        except Exception as e:
            sys.stderr.write(f"normalize-findings.py: SQLite store failed (non-critical): {e}\n")

    _ = doc
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))